/**
 * Dynamically simulates live heartbeat fluctuations for realistic demo visualization
 */
export function simulateNodeTick(node: ThemeNode): ThemeNode {
  if (!node.is_online) return node;

  const jitter = (val: number, spread: number, min = 0, max = 100) => {
    const delta = (Math.random() - 0.48) * spread;
    return Math.max(min, Math.min(max, Number((val + delta).toFixed(1))));
  };

  const newCpu = jitter(node.cpu, 4.5, 2, 98);
  const newMem = jitter(node.mem, 0.8, 10, 95);
  const memUsed = Math.round((newMem / 100) * node.mem_total);

  // Network speed spikes
  const speedFactor = 0.85 + Math.random() * 0.35;
  const newDown = Math.max(1024, Math.round(node.rate_down * speedFactor));
  const newUp = Math.max(1024, Math.round(node.rate_up * speedFactor));

  return {
    ...node,
    cpu: newCpu,
    mem: newMem,
    mem_used: memUsed,
    rate_down: newDown,
    rate_up: newUp,
    traffic_down: (node.traffic_down || 0) + Math.round(newDown * 1.5),
    traffic_up: (node.traffic_up || 0) + Math.round(newUp * 1.5),
  };
}
